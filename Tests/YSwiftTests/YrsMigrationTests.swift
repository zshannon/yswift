struct YrsMigrationTests {
    @Test(arguments: [UInt64(0), (UInt64(1) << 32) + 17, (UInt64(1) << 53) - 1])
    func clientIDsRoundTripWithoutTruncation(clientID: UInt64) async throws {
        let source = YDocument(options: YDocumentOptions(clientId: clientID))
        let remote = YDocument(options: YDocumentOptions(clientId: 9))
        let sourceText = source.getOrCreateText(named: "text")
        let remoteText = remote.getOrCreateText(named: "text")
        #expect(source.clientId == clientID)
        await sourceText.append("hello 🌍")
        let first = await source.transact { $0.transactionEncodeStateAsUpdate() }
        try await remote.transact { try $0.transactionApplyUpdate(update: first) }
        // This insertion references an item from the original high-ID client.
        await remoteText.append("!")
        let reply = await remote.transact { $0.transactionEncodeStateAsUpdate() }
        try await source.transact { try $0.transactionApplyUpdate(update: reply) }
        #expect(await sourceText.getStringAsync() == "hello 🌍!")
        #expect(await remoteText.getStringAsync() == "hello 🌍!")
    }

    @Test
    func readsLegacy025Update() async throws {
        // Generated by yrs = "=0.25.0", Doc::with_client_id(42), using encode_state_as_update_v1.
        let update: [UInt8] = [1, 3, 42, 0, 8, 1, 5, 105, 116, 101, 109, 115, 1, 119, 6, 108, 101, 103, 97, 99, 121, 40, 1, 4, 114, 111, 111, 116, 5, 99, 111, 117, 110, 116, 1, 125, 7, 4, 1, 4, 116, 101, 120, 116, 7, 104, 105, 32, 240, 159, 140, 141, 0]
        let document = YDocument()
        try await document.transact { try $0.transactionApplyUpdate(update: update) }
        let array: YArray<String> = document.getOrCreateArray(named: "items")
        let map: YMap<Int> = document.getOrCreateMap(named: "root")
        let text = document.getOrCreateText(named: "text")
        #expect(await array.toArrayAsync() == ["legacy"])
        #expect(await map.get(key: "count") == 7)
        #expect(await text.getStringAsync() == "hi 🌍")
        await text.append("!")
        #expect(await text.getStringAsync() == "hi 🌍!")
    }

    @Test
    func integersAndFractionsSurviveReplication() async throws {
        let source = YDocument()
        let target = YDocument()
        let integers: YMap<Int64> = source.getOrCreateMap(named: "integers")
        let fractions: YArray<Double> = source.getOrCreateArray(named: "fractions")
        await integers.set(9_007_199_254_740_991, forKey: "max")
        await integers.set(-9_007_199_254_740_991, forKey: "min")
        await fractions.append(1.25)
        let update = await source.transact { $0.transactionEncodeStateAsUpdate() }
        try await target.transact { try $0.transactionApplyUpdate(update: update) }
        let receivedIntegers: YMap<Int64> = target.getOrCreateMap(named: "integers")
        let receivedFractions: YArray<Double> = target.getOrCreateArray(named: "fractions")
        #expect(await receivedIntegers.toMapAsync() == ["max": 9_007_199_254_740_991, "min": -9_007_199_254_740_991])
        #expect(await receivedFractions.toArrayAsync() == [1.25])
    }

    @Test
    func invalidUTF8IsRejected() async throws {
        let source = YDocument(options: YDocumentOptions(clientId: 7))
        let text = source.getOrCreateText(named: "text")
        await text.append("valid")
        var update = await source.transact { $0.transactionEncodeStateAsUpdate() }
        let index = try #require(update.firstIndex(of: 118)) // "v" in "valid"
        update[index] = 255
        let malformed = update
        let target = YDocument()
        await #expect(throws: (any Error).self) {
            try await target.transact { try $0.transactionApplyUpdate(update: malformed) }
        }
        #expect(await target.getOrCreateText(named: "text").getStringAsync() == "")
    }

    @Test
    func outOfOrderUpdatesConverge() async throws {
        let source = YDocument(options: YDocumentOptions(clientId: (1 << 40) + 3))
        let text = source.getOrCreateText(named: "text")
        let first = await source.transact { transaction in
            text.append("a", in: transaction)
            return transaction.transactionEncodeUpdate()
        }
        let second = await source.transact { transaction in
            text.append("b", in: transaction)
            return transaction.transactionEncodeUpdate()
        }
        let target = YDocument()
        try await target.transact { try $0.transactionApplyUpdate(update: second) }
        try await target.transact { try $0.transactionApplyUpdate(update: first) }
        // Reapplying the same update is idempotent.
        try await target.transact { try $0.transactionApplyUpdate(update: second) }
        #expect(await target.getOrCreateText(named: "text").getStringAsync() == "ab")
    }

    @Test
    func keyedObserversReplaceAndRemoveIndependently() async {
        await confirmation("Replaced observer receives nothing", expectedCount: 0) { replaced in
            await confirmation("Replacement receives only the first change") { replacement in
                await confirmation("Independent observer receives both changes", expectedCount: 2) { other in
                    let document = YDocument()
                    let text = document.getOrCreateText(named: "text")
                    document.transactSync { transaction in
                        #expect(text.observe(key: "replace", transaction: transaction) { _ in replaced() })
                        #expect(text.observe(key: "replace", transaction: transaction) { _ in replacement() })
                        #expect(text.observe(key: "other", transaction: transaction) { _ in other() })
                        text.append("a", in: transaction)
                    }
                    document.transactSync { transaction in
                        #expect(text.unobserve(key: "replace", transaction: transaction))
                        text.append("b", in: transaction)
                    }
                    document.transactSync { transaction in
                        #expect(text.unobserve(key: "other", transaction: transaction))
                    }
                }
            }
        }
    }

    @Test
    func deletedNestedCollectionCanBeUnobservedSafely() {
        let document = YDocument()
        let root: YMap<String> = document.getOrCreateMap(named: "root")
        let nested: YMap<Int> = document.transactSync { transaction in
            root.insertMap(forKey: "nested", transaction: transaction)
        }
        document.transactSync { transaction in
            #expect(nested.observe(key: "nested", transaction: transaction) { _ in })
            root.removeValue(forKey: "nested", transaction: transaction)
        }
        document.transactSync { transaction in
            #expect(!nested.unobserve(key: "nested", transaction: transaction))
            #expect(!nested.observe(key: "nested", transaction: transaction) { _ in })
        }
    }

    @Test
    func streamsAreRegisteredBeforeReturning() async throws {
        try await confirmation("Each stream receives its first change", expectedCount: 3) { received in
            let document = YDocument()
            let array: YArray<Int> = document.getOrCreateArray(named: "array")
            let map: YMap<Int> = document.getOrCreateMap(named: "map")
            let text = document.getOrCreateText(named: "text")
            var arrayEvents = await array.observeAsync().makeAsyncIterator()
            var mapEvents = await map.observeAsync().makeAsyncIterator()
            var textEvents = await text.observeAsync().makeAsyncIterator()
            await array.append(7)
            await map.set(8, forKey: "value")
            await text.append("hello")
            let arrayChange = try #require(await arrayEvents.next())
            received()
            #expect(arrayChange == [.added(elements: [7])])
            let mapChange = try #require(await mapEvents.next())
            received()
            #expect(mapChange == [.inserted(key: "value", value: 8)])
            let textChange = try #require(await textEvents.next())
            received()
            if case .inserted(let value, _) = textChange.first {
                #expect(try JSONDecoder().decode(String.self, from: Data(value.utf8)) == "hello")
            } else {
                Issue.record("Expected a text insertion")
            }
        }
    }

    @Test
    func cancellingStreamConsumerDoesNotCancelOtherObservers() async throws {
        try await confirmation("Cancelled consumer receives nothing", expectedCount: 0) { cancelled in
            try await confirmation("Independent consumer still receives changes") { received in
                let document = YDocument()
                let map: YMap<Int> = document.getOrCreateMap(named: "map")
                let cancelledStream = await map.observeAsync()
                var remaining = await map.observeAsync().makeAsyncIterator()
                let consumer = Task {
                    for await _ in cancelledStream {
                        cancelled()
                    }
                }
                consumer.cancel()
                await consumer.value
                await map.set(42, forKey: "value")
                let event = try #require(await remaining.next())
                received()
                #expect(event == [.inserted(key: "value", value: 42)])
            }
        }
    }

    @Test
    func subdocumentLifecycleStreams() async throws {
        try await confirmation("Receives insertion and destruction", expectedCount: 2) { received in
            let parent = YDocument()
            let subdoc = YDocument()
            let children: YArray<String> = parent.getOrCreateArray(named: "children")
            var lifecycle = await parent.observeSubdocsAsync().makeAsyncIterator()
            var destruction = await subdoc.observeDestroyAsync().makeAsyncIterator()
            await parent.transact { transaction in
                children.insertSubdoc(at: 0, subdoc, transaction: transaction)
            }
            let event = try #require(await lifecycle.next())
            received()
            #expect(event.added.map(\.guid) == [subdoc.guid])
            await parent.transact { subdoc.destroy(in: $0) }
            _ = try #require(await destruction.next())
            received()
            #expect(await destruction.next() == nil)
        }
    }

    @Test
    func undoObserverCanAwaitSafeRemoval() async throws {
        try await confirmation("Receives the original entry once") { received in
            let document = YDocument()
            let text = document.getOrCreateText(named: "text")
            let manager: YUndoManager = try document.undoManager(trackedRefs: [text], timestamp: { 1 })
            let (removals, completion) = AsyncStream<Bool>.makeStream()
            try manager.observeAdded(key: "added") { _, metadata in
                received()
                Task {
                    completion.yield(try await manager.unobserveAdded(key: "added"))
                    completion.finish()
                }
                return metadata
            }
            document.transactSync { text.append("hello", in: $0) }
            var iterator = removals.makeAsyncIterator()
            #expect(await iterator.next() == true)
            #expect(try manager.undo())
            #expect(try manager.redo())
        }
    }

    @Test
    func emptyUndoManagerCanTrackLater() throws {
        let document = YDocument()
        let manager: YUndoManager = try document.undoManager(trackedRefs: [], timestamp: { 1 })
        let text = document.getOrCreateText(named: "text")
        try manager.track(text)
        document.transactSync { text.append("hello", in: $0) }
        #expect(try manager.undo())
        #expect(text.getString() == "")
    }
}
